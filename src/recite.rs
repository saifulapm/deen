//! Record a recitation, transcribe it, and say which words were right.
//!
//! Transcription is `voxtype transcribe`, a one-shot subcommand that has
//! nothing to do with voxtype's dictation daemon — starting a recitation never
//! disturbs Alt-Alt, and Alt-Alt never disturbs this.

use std::{
    fs,
    io::{BufRead, Read},
    path::{Path, PathBuf},
    process::{Command, Stdio},
    sync::mpsc,
    thread,
    time::Duration,
};

use anyhow::{anyhow, bail, Context, Result};

/// The Quran-tuned model. `DEEN_MODEL` overrides.
fn model_path() -> PathBuf {
    if let Ok(p) = std::env::var("DEEN_MODEL") {
        return PathBuf::from(p);
    }
    home().join(".local/share/voxtype/models/ggml-quran-base-q8.bin")
}

fn home() -> PathBuf {
    PathBuf::from(std::env::var("HOME").unwrap_or_default())
}

fn cache_dir() -> PathBuf {
    std::env::var("XDG_CACHE_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|_| home().join(".cache"))
        .join("deen")
}

/// Write the voxtype config this crate transcribes under, if it is missing.
///
/// THREE THINGS HERE ARE LOAD-BEARING, each found the hard way:
///
/// 1. THE MODEL PATH MUST BE IN THE CONFIG. `voxtype --model <absolute path>`
///    is documented and accepted, and then silently ignored by `transcribe`,
///    which loads the *configured* model instead — the run cheerfully logs
///    `Loading whisper model from ".../ggml-base.en.bin"` while claiming to
///    honour the flag. Every early result in this project came from the
///    English dictation model because of it.
///
/// 2. THE PROMPT MUST BE ARABIC, AND MUST NOT BE QURAN. voxtype's own config
///    carries a dictation prompt ("Technical discussion about Laravel, PHP,
///    React, TypeScript…") which biases so hard toward English that Quranic
///    audio comes back as Latin transliteration — `Bismillahir Rahmanir
///    Rahim`. Clearing it is not enough; the Arabic script only anchors once
///    the prompt is itself Arabic. It must not be an ayah either, or the
///    decode is being handed its own answer.
///
/// 3. THIS IS A SEPARATE FILE FROM THE USER'S CONFIG, on purpose. Their
///    dictation setup is theirs; we pass `-c` and leave it alone.
fn whisper_config() -> Result<PathBuf> {
    let dir = cache_dir();
    fs::create_dir_all(&dir).with_context(|| format!("cannot create {}", dir.display()))?;
    let path = dir.join("whisper.toml");
    let model = model_path();
    if !model.exists() {
        bail!(
            "the Quran model is missing at {} — run the installer",
            model.display()
        );
    }
    let want = format!(
        concat!(
            "# Generated by deen. Edits are overwritten; this is derived state.\n",
            "state_file = \"disabled\"\n\n",
            "[hotkey]\nenabled = false\n\n",
            // Whisper hallucinates words onto silence — three seconds of a
            // quiet room came back as `الظُّسُودُ`, which the scorer would
            // then report as a mispronounced ٱلرَّحِيمِ. Telling someone they
            // recited a word wrong when they said nothing at all is the worst
            // output this tool can produce, so VAD gates it: no speech means
            // an empty transcription and an honest "I did not hear anything".
            "[vad]\nenabled = true\n\n",
            "[whisper]\n",
            "model = \"{}\"\n",
            "language = \"ar\"\n",
            "initial_prompt = \"هذا تسجيل صوتي باللغة العربية الفصحى.\"\n",
        ),
        model.display()
    );
    // Rewrite when the model path moves, so switching quantisation is one env
    // var and not a stale config that silently keeps the old model.
    if fs::read_to_string(&path).map(|c| c != want).unwrap_or(true) {
        fs::write(&path, &want).with_context(|| format!("cannot write {}", path.display()))?;
    }
    Ok(path)
}

/// Transcribe a 16 kHz mono WAV. Returns what the model heard.
pub fn transcribe(wav: &Path) -> Result<String> {
    let cfg = whisper_config()?;
    let out = Command::new("voxtype")
        .arg("-c")
        .arg(&cfg)
        .arg("transcribe")
        .arg(wav)
        .output()
        .context("cannot run voxtype — is it installed?")?;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        bail!(
            "voxtype failed: {}",
            err.lines().last().unwrap_or("no output").trim()
        );
    }
    Ok(parse_transcription(&String::from_utf8_lossy(&out.stdout)))
}

/// Pull the recitation out of voxtype's stdout.
///
/// voxtype prints its progress log to stdout alongside the result, so the
/// transcription is the last non-empty line rather than the whole stream.
///
/// The subtlety is silence. When VAD finds no speech voxtype says so IN PROSE
/// and prints no transcription, so the "last line" rule would hand that
/// sentence back as if it were the recitation and the scorer would earnestly
/// align "No speech detected, skipping transcription." against the ayah. An
/// empty result is the honest answer, and the caller renders it as "nothing
/// heard" instead of as a wrong recitation.
fn parse_transcription(stdout: &str) -> String {
    let last = stdout
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .next_back()
        .unwrap_or("");
    if last.starts_with("No speech detected") || last.starts_with("VAD:") {
        return String::new();
    }
    last.to_string()
}

/// Whether the default capture source is muted, via wpctl.
fn mic_muted() -> bool {
    Command::new("wpctl")
        .args(["get-volume", "@DEFAULT_AUDIO_SOURCE@"])
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).contains("MUTED"))
        .unwrap_or(false)
}

fn set_mic_mute(muted: bool) {
    let _ = Command::new("wpctl")
        .args([
            "set-mute",
            "@DEFAULT_AUDIO_SOURCE@",
            if muted { "1" } else { "0" },
        ])
        .status();
}

/// Record until stdin closes (or a line arrives), or `max` elapses.
///
/// THE MICROPHONE IS MUTED AT REST ON THIS MACHINE and that is the correct
/// privacy posture — the bar's Mic widget and XF86AudioMicMute maintain it,
/// and bin/voxtype-mic-gate exists because voxtype recorded digital silence
/// for weeks without noticing. PipeWire hands a muted source to whoever asks
/// and reports no error, so a recitation would score zero for a reason that
/// has nothing to do with the reciter. We open the microphone for exactly the
/// length of one recitation and put it back the way we found it — including
/// on the error paths, which is why the restore is not written after a `?`.
///
/// The stop protocol is stdin EOF rather than a signal so that a caller which
/// is not a shell — the hub panel — can end a recording by closing a pipe,
/// with no PID handling and no signal crate.
pub fn record(dest: &Path, max: Duration) -> Result<()> {
    let was_muted = mic_muted();
    if was_muted {
        set_mic_mute(false);
    }
    let result = record_inner(dest, max);
    if was_muted {
        set_mic_mute(true);
    }
    result
}

fn record_inner(dest: &Path, max: Duration) -> Result<()> {
    let mut child = Command::new("pw-record")
        .args(["--rate", "16000", "--channels", "1", "--format", "s16"])
        .arg(dest)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()
        .context("cannot run pw-record — is pipewire-utils installed?")?;

    let (tx, rx) = mpsc::channel();
    thread::spawn(move || {
        // Either a line or EOF means stop; both show up as a finished read.
        let mut line = String::new();
        let _ = std::io::stdin().lock().read_line(&mut line);
        let _ = tx.send(());
    });
    let _ = rx.recv_timeout(max);

    // SIGTERM, not Child::kill() — that is SIGKILL, and pw-record would never
    // get to write the RIFF length back into the header, leaving a WAV that
    // whisper refuses to open.
    let _ = Command::new("kill")
        .args(["-TERM", &child.id().to_string()])
        .status();
    let status = child.wait().context("pw-record did not exit")?;

    if !dest.exists() {
        let mut err = String::new();
        if let Some(mut s) = child.stderr.take() {
            let _ = s.read_to_string(&mut err);
        }
        return Err(anyhow!(
            "pw-record wrote nothing ({status}) {}",
            err.trim()
        ));
    }
    Ok(())
}

/// A scratch path for one recitation. Recordings are never kept: they are the
/// user's voice, they are worthless once scored, and nothing in this project
/// uploads anything.
pub fn scratch_wav() -> Result<PathBuf> {
    let dir = std::env::var("XDG_RUNTIME_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| PathBuf::from("/tmp"))
        .join("deen");
    fs::create_dir_all(&dir).with_context(|| format!("cannot create {}", dir.display()))?;
    Ok(dir.join(format!("recite-{}.wav", std::process::id())))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn takes_the_transcription_not_the_log() {
        let out = "INFO Loading whisper model from \"/x/y.bin\"\n\
                   INFO Transcription completed in 1.35s: \"a b\"\n\
                   \n\
                   إِيَّاكَ نَعْبُدُ\n";
        assert_eq!(parse_transcription(out), "إِيَّاكَ نَعْبُدُ");
    }

    #[test]
    fn silence_is_empty_not_the_prose_voxtype_prints() {
        let out = "VAD: 0.00s speech (0.0% of audio)\n\
                   No speech detected, skipping transcription.\n";
        assert_eq!(parse_transcription(out), "");
    }

    #[test]
    fn empty_output_is_empty() {
        assert_eq!(parse_transcription(""), "");
        assert_eq!(parse_transcription("\n  \n"), "");
    }
}
